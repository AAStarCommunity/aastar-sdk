#!/usr/bin/env tsx
/**
 * Proof (DSR 2026-11-19, post-tag PR A): the functions and events the rc.8 live cells and the read-back gate call on
 * SP-deployed contracts outside the seven vendored 5.5.0 files have the same selector, inputs, outputs (names
 * included), state mutability, topic0 and indexed layout in the SDK's vendored ABIs as in SuperPaymaster's COMPILED
 * artifacts at the pinned commit. Records the compiled side into packages/core/src/abis/fixtures/coexist-stack-abi.json
 * and the comparison into docs/onchain-evidence/coexist-stack-abi-equality.md.
 *
 *   SP_REPO=<SuperPaymaster checkout at the commit, built: forge build> SP_COMMIT=<40-hex> pnpm exec tsx scripts/coexist-stack-abi-pin.ts
 *
 * Refuses unless the checkout's HEAD is SP_COMMIT and its tree is clean. A clean tree does not prove out/ was built
 * from it (ignored artifacts survive a checkout): build fresh before recording. `--verify` writes nothing and exits 1
 * unless the committed fixture equals what this out/ gives; CI runs it on its own fresh forge build of the commit.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { canonicalEntry } from '../packages/core/src/abis/paperPathAbi.js';
import { COEXIST_STACK_ENTRIES, coexistEntriesFor, scannedGetters } from '../packages/core/src/abis/coexistStackAbi.js';

const SDK_ROOT = process.cwd();
const SP_REPO = path.resolve(SDK_ROOT, process.env.SP_REPO ?? '../SuperPaymaster');
const COMMIT = process.env.SP_COMMIT ?? '';
if (!/^[0-9a-f]{40}$/.test(COMMIT)) throw new Error('SP_COMMIT must be a full 40-hex commit');
const git = (...a: string[]) => execFileSync('git', ['-C', SP_REPO, ...a], { encoding: 'utf8' }).trim();
if (git('rev-parse', 'HEAD') !== COMMIT) throw new Error(`${SP_REPO} is not at ${COMMIT}`);
if (git('status', '--porcelain', '--untracked-files=no') !== '') throw new Error(`${SP_REPO} has local changes; the compiled out/ would not be the commit's`);

const VERIFY = process.argv.includes('--verify');
const FIXTURE = path.join(SDK_ROOT, 'packages/core/src/abis/fixtures/coexist-stack-abi.json');
const abiOf = (text: string) => { const j = JSON.parse(text); return Array.isArray(j) ? j : j.abi; };
const fixture: any = { spCommit: COMMIT, files: {} as Record<string, any> };
const rows: string[] = [];
let mismatches = 0;
for (const [file, spec] of Object.entries(COEXIST_STACK_ENTRIES)) {
    const sdkAbi = abiOf(readFileSync(path.join(SDK_ROOT, 'packages/core/src/abis', file), 'utf8'));
    const compiled = abiOf(readFileSync(path.join(SP_REPO, 'out', spec.artifact), 'utf8'));
    const entries = coexistEntriesFor(file, sdkAbi);
    // The compiled contract's own address getters: one the SDK file lacks is a getter the gate's scan never reads.
    const compiledScanned = scannedGetters(compiled).map((w) => w.name).sort();
    const sdkScanned = scannedGetters(sdkAbi).map((w) => w.name).sort();
    fixture.files[file] = { artifact: spec.artifact, compiledScanned, entries: entries.map((w) => ({ ...w, compiled: canonicalEntry(compiled, w) ?? null })) };
    if (spec.scanned && JSON.stringify(compiledScanned) !== JSON.stringify(sdkScanned)) {
        mismatches++;
        rows.push(`| ${file} | scan coverage | getters ${JSON.stringify(sdkScanned)} | getters ${JSON.stringify(compiledScanned)} | **NO** |`);
    }
    for (const w of entries) {
        const mine = canonicalEntry(sdkAbi, w), theirs = canonicalEntry(compiled, w);
        const same = !!mine && !!theirs && mine.signature === theirs.signature && mine.selector === theirs.selector;
        if (!same) mismatches++;
        rows.push(`| ${file} | ${w.type} ${w.name} | \`${mine?.signature ?? '(absent)'}\` | \`${theirs?.signature ?? '(absent)'}\` | ${same ? 'yes' : '**NO**'} |`);
    }
}
if (VERIFY) {
    const committed = readFileSync(FIXTURE, 'utf8');
    const same = committed === JSON.stringify(fixture, null, 2) + '\n';
    console.log(same ? `PASS — the committed fixture equals the compiled artifacts at ${COMMIT} (${mismatches} mismatches)` : `FAIL — the committed fixture differs from the compiled artifacts at ${COMMIT}: re-record it`);
    process.exit(same && mismatches === 0 ? 0 : 1);
}
writeFileSync(FIXTURE, JSON.stringify(fixture, null, 2) + '\n');
const doc = [
    '# rc.8 coexisting stack: the ABI entries the live cells and the gate use outside the seven 5.5.0 files',
    '',
    `Generated by \`scripts/coexist-stack-abi-pin.ts\` against SuperPaymaster's compiled artifacts (\`forge build\`) at commit ${COMMIT} (tag v5.5.0-rc.8). Each row compares the SDK's vendored entry with the compiled one: full signature (inputs and outputs with names, state mutability; events with indexed flags and anonymity) and selector / topic0.`,
    '',
    'Entries: the explicit calls of the read-back gate and the four live cells (S1, S1r, S3b, C12), plus every no-argument address-carrying getter of every ABI the gate\'s exhaustive scan reads; a file whose compiled contract has an address getter the vendored file lacks is a mismatch (the scan would not read it). TimelockController has no such getter on either side, so it contributes no rows. The first run against rc.8 found two such gaps — the SDK-wide Registry.json lacks `pendingOwner()`, and the book\'s gToken is GTokenAuthorization (DeployLive.s.sol:23, :91) whose `factory()` / `mySBT()` GToken.json lacks — so the rc.8 stack reads those two through the coexist set rc8/Registry.json and rc8/GTokenAuthorization.json (SP blobs at this commit, byte-identical to the compiled ABI; scripts/check-sp550-abis.ts) and the SDK-wide files stay as they are for 5.4.2. EntryPoint, SimpleAccount and the task token are not SuperPaymaster contracts (standard interfaces) and are not listed.',
    '',
    '| File | Entry | SDK vendored | rc.8 compiled | Equal |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    `Verdict: ${mismatches === 0 ? 'PASS — every entry the rc.8 stack reads, through the SDK-wide files or the rc8/ coexist set, equals the compiled rc.8 ABI' : `FAIL — ${mismatches} entr${mismatches === 1 ? 'y differs' : 'ies differ'}: those contracts need an rc.8 coexist vendored set`}`,
    '',
];
writeFileSync(path.join(SDK_ROOT, 'docs/onchain-evidence/coexist-stack-abi-equality.md'), doc.join('\n'));
console.log(doc.slice(-2).join('\n'));
process.exitCode = mismatches === 0 ? 0 : 1;
