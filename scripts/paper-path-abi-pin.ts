#!/usr/bin/env tsx
/**
 * Records, from SuperPaymaster's committed abis/ at one commit, the full signature and selector of every function and
 * event the paper's four gasless paths (and the xPNTs v2 credit API) use, so the SDK's vendored ABIs can be checked
 * against it without the SP repo (packages/core/src/abis/paperPathAbi.test.ts).
 *
 *   SP_REPO=../SuperPaymaster SP_COMMIT=<40-hex> pnpm exec tsx scripts/paper-path-abi-pin.ts
 *
 * Reads git blobs (`git show <commit>:<path>`), never the SP working tree. Writes
 * packages/core/src/abis/fixtures/paper-path-abi.json and docs/onchain-evidence/paper-path-abi-equality.md.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import * as path from 'node:path';
import { PAPER_PATH_ENTRIES, canonicalEntry } from '../packages/core/src/abis/paperPathAbi.js';

const SDK_ROOT = process.cwd();
const SP_REPO = path.resolve(SDK_ROOT, process.env.SP_REPO ?? '../SuperPaymaster');
const COMMIT = process.env.SP_COMMIT ?? '';
if (!/^[0-9a-f]{40}$/.test(COMMIT)) throw new Error('SP_COMMIT must be a full 40-hex commit');
const git = (...args: string[]) => execFileSync('git', ['-C', SP_REPO, ...args], { encoding: 'utf8', maxBuffer: 64 << 20 });
if (git('cat-file', '-t', COMMIT).trim() !== 'commit') throw new Error(`${COMMIT} is not a commit in ${SP_REPO}`);

const abiOf = (text: string) => { const j = JSON.parse(text); return Array.isArray(j) ? j : j.abi; };
const fixture: any = { spCommit: COMMIT, files: {} as Record<string, any> };
const rows: string[] = [];
for (const [sdkFile, { upstream, entries }] of Object.entries(PAPER_PATH_ENTRIES)) {
    const blob = git('show', `${COMMIT}:${upstream}`);
    const sdkText = readFileSync(path.join(SDK_ROOT, 'packages/core/src/abis', sdkFile), 'utf8');
    const up = abiOf(blob), sdk = abiOf(sdkText);
    const out: any[] = [];
    for (const want of entries) {
        const u = canonicalEntry(up, want), s = canonicalEntry(sdk, want);
        if (!u) throw new Error(`${upstream}@${COMMIT}: no ${want.type} ${want.name}`);
        out.push(u);
        rows.push(`| ${sdkFile} | ${want.type} ${want.name} | \`${u.signature}\` | ${u.selector} | ${s ? s.selector : 'missing'} | ${s && s.signature === u.signature && s.selector === u.selector ? 'yes' : '**NO**'} |`);
    }
    fixture.files[sdkFile] = { upstream, upstreamBlobSha256: createHash('sha256').update(blob).digest('hex'), entries: out };
}
mkdirSync(path.join(SDK_ROOT, 'packages/core/src/abis/fixtures'), { recursive: true });
writeFileSync(path.join(SDK_ROOT, 'packages/core/src/abis/fixtures/paper-path-abi.json'), JSON.stringify(fixture, null, 2) + '\n');
const pass = !rows.some((r) => r.includes('**NO**'));
const md = [
    '# Paper-path ABI entries: SDK vendored files vs SuperPaymaster',
    '',
    `Generated by \`scripts/paper-path-abi-pin.ts\` from SuperPaymaster \`abis/\` git blobs at ${COMMIT} (blob sha256 in packages/core/src/abis/fixtures/paper-path-abi.json). Function signatures include outputs and state mutability; event signatures include which inputs are indexed. Selectors are the 4-byte function selector or the 32-byte event topic.`,
    '',
    '| SDK file | Entry | Signature at SP | Selector at SP | Selector in SDK | Identical |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
    `Verdict: ${pass ? 'PASS — every listed entry is identical, so the paper paths can run on the vendored ABIs' : 'FAIL'}`,
    '',
];
writeFileSync(path.join(SDK_ROOT, 'docs/onchain-evidence/paper-path-abi-equality.md'), md.join('\n'));
console.log(md.join('\n'));
if (!pass) process.exitCode = 1;
