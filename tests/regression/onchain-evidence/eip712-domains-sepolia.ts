/**
 * Evidence: the EIP-712 domains of the contracts without the full eip712Domain() + DOMAIN_SEPARATOR() pair, read
 * on Sepolia, and the KMS payment-signer pre-checks against them. Read-only (eth_call / eth_getCode on a public RPC);
 * nothing is signed or sent.
 *
 *   pnpm exec tsx tests/regression/onchain-evidence/eip712-domains-sepolia.ts
 *
 * Output: docs/onchain-evidence/eip712-domains-sepolia.md (no RPC URL, no error text).
 */
import { writeFileSync } from 'node:fs';
import { createPublicClient, http, keccak256, toHex, type Address, type Hex } from 'viem';
import { sepolia } from 'viem/chains';
import {
    resolveReportedEip712Domain, verifyPinnedEip712Domain, resolveEip712Domain, getCanonicalAddresses, MicroPaymentChannelABI,
} from '@aastar/core';
import { X402_FACILITATOR_DOMAIN, X402_PAYMENT_AUTHORIZATION_TYPE_STRING } from '@aastar/x402';
import { micropaymentVoucherDigest, micropaymentVoucherContractDigest } from '../../../packages/airaccount/src/server/services/kms-payment-signer.js';

const RPC = process.env.SEPOLIA_PUBLIC_RPC ?? 'https://ethereum-sepolia-rpc.publicnode.com'; // never written out
const OUT = 'docs/onchain-evidence/eip712-domains-sepolia.md';
const FACILITATOR = '0xfe1DB01e1d6622e722B92ed5993af61325DB92aF' as Address; // DEFAULT_X402_FACILITATORS[11155111]

// Only the SDK's own refusal reason is recorded, never error text.
const reasonOf = (e: unknown) => {
    const r = (e as any)?.data?.reason;
    return (e as any)?.name === 'AAStarError' && typeof r === 'string' && /^[a-z-]+$/.test(r) ? r : 'unexpected-error';
};
const json = (v: unknown) => JSON.stringify(v, (_k, x) => (typeof x === 'bigint' ? x.toString() : x));

async function main() {
    const c = createPublicClient({ chain: sepolia, transport: http(RPC) });
    if ((await c.getChainId()) !== sepolia.id) throw new Error('the endpoint is not Sepolia');
    const block = await c.getBlockNumber();
    const book = getCanonicalAddresses(sepolia.id)!;
    const channel = book.microPaymentChannel as Address;
    const rows: Array<[string, string, boolean]> = [];

    const ch = await resolveReportedEip712Domain(c as any, channel, { expectedChainId: sepolia.id });
    rows.push([`MicroPaymentChannel ${channel}: eip712Domain()`, `${json(ch.domain)}; DOMAIN_SEPARATOR() present: ${ch.separatorChecked}`, ch.domain.name === 'MicroPaymentChannel' && ch.domain.version === '1.0.0']);
    const onChainTypeHash = await c.readContract({ address: channel, abi: MicroPaymentChannelABI, functionName: 'VOUCHER_TYPEHASH', args: [] }) as Hex;
    const u128 = keccak256(toHex('Voucher(bytes32 channelId,uint128 cumulativeAmount)'));
    const u256 = keccak256(toHex('Voucher(bytes32 channelId,uint256 cumulativeAmount)'));
    rows.push([`MicroPaymentChannel VOUCHER_TYPEHASH`, `${onChainTypeHash} (= uint128 type: ${onChainTypeHash === u128}; = uint256 type: ${onChainTypeHash === u256})`, onChainTypeHash === u128]);

    const voucher = { keyId: 'k', chainId: sepolia.id, verifyingContract: channel, channelId: ('0x' + '11'.repeat(32)), cumulativeAmount: '1000000' };
    const kms = micropaymentVoucherDigest(voucher), contract = micropaymentVoucherContractDigest(voucher);
    rows.push(['KMS voucher digest vs the digest the channel verifies (same voucher)', `KMS ${kms}; contract ${contract}`, kms !== contract]);

    const fac = await verifyPinnedEip712Domain(c as any, FACILITATOR, { ...X402_FACILITATOR_DOMAIN, typeStrings: [X402_PAYMENT_AUTHORIZATION_TYPE_STRING] }, { expectedChainId: sepolia.id });
    rows.push([`X402Facilitator ${FACILITATOR}: code contains the pinned domain constants`, `${json(fac.domain)}; DOMAIN_SEPARATOR() present: ${fac.separatorChecked}`, true]);
    let typo: string;
    try { await verifyPinnedEip712Domain(c as any, FACILITATOR, { name: 'X402Facilitatr', version: '1', typeStrings: [] }); typo = 'accepted'; } catch (e) { typo = `refused: ${reasonOf(e)}`; }
    rows.push(['X402Facilitator with a misspelled pinned name', typo, typo === 'refused: code-lacks-domain-constants']);

    const g = await resolveEip712Domain(c as any, book.gToken as Address);
    rows.push([`GToken ${book.gToken}: domain (checked against DOMAIN_SEPARATOR())`, json(g.domain), g.domain.name === 'GToken' && g.domain.version === '1']);

    const pass = rows.every(([, , ok]) => ok);
    const lines = [
        '# EIP-712 domains on Sepolia (contracts without the full getter pair) and the KMS pre-checks',
        '',
        `Generated by \`tests/regression/onchain-evidence/eip712-domains-sepolia.ts\` on ${new Date().toISOString()}, Sepolia block ${block}, read-only through a public RPC (URL not recorded).`,
        '',
        '| Check | Result | OK |',
        '|---|---|---|',
        ...rows.map(([what, got, ok]) => `| ${what} | ${got} | ${ok ? 'yes' : '**NO**'} |`),
        '',
        `Verdict: ${pass ? 'PASS' : 'FAIL'}`,
        '',
    ];
    writeFileSync(OUT, lines.join('\n'));
    console.log(lines.join('\n'));
    if (!pass) process.exitCode = 1;
}

main().catch((e) => { console.error(`eip712-domains-sepolia: ${reasonOf(e)}`); process.exitCode = 1; });
